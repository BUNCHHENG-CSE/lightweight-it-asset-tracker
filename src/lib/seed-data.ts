/**
 * Helper to generate an ISO date string (YYYY-MM-DD) offset by `daysOffset` from today.
 * Using relative offsets ensures warranty expiry (<=60d) and EOL (<=90d) alerts
 * are always fresh and realistic whenever the app is run.
 */
function offsetDate(daysOffset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().slice(0, 10);
}

